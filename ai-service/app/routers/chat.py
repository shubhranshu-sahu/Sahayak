import logging
from typing import Optional
from fastapi import APIRouter, Depends, Query, status
from fastapi.responses import StreamingResponse
from app.dependencies.auth import get_current_secretary
from app.models.chat import ChatRequest, HistoryResponse
from app.services import chat_service, history_service

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/chat", tags=["Chat"])


@router.post(
    "/message",
    summary="Send a message and stream AI response",
    description="Streams the AI assistant's response live via Server-Sent Events (SSE). Requires valid secretary JWT.",
    response_class=StreamingResponse,
    status_code=status.HTTP_200_OK,
)
async def send_chat_message(
    request: ChatRequest,
    current_user: dict = Depends(get_current_secretary),
):
    """
    Primary chat endpoint.
    - Requires Authorization: Bearer <jwt> header issued by the Node.js backend.
    - Automatically overrides and binds secretary_id and thread_id to the verified token's userId.
    - Saves the secretary's message to MongoDB permanent history.
    - Streams tokens generated by LangGraph in real time via SSE (text/event-stream).
    - Automatically persists the complete AI reply to MongoDB upon stream completion.
    """
    # Security: enforce caller's verified userId from the JWT payload
    verified_secretary_id = current_user["user_id"]
    request.secretary_id = verified_secretary_id
    request.thread_id = f"secretary_{verified_secretary_id}"

    # Security: bind verified society_id from token claims
    token_society_id = current_user.get("society_id")
    if token_society_id is not None:
        try:
            request.society_id = int(token_society_id)
        except (ValueError, TypeError):
            pass

    # Populate optional contextual defaults from JWT payload if available
    raw_payload = current_user.get("raw_payload", {})
    if not request.secretary_name or request.secretary_name == "Secretary":
        name = raw_payload.get("name") or raw_payload.get("userName")
        if name:
            request.secretary_name = name
    if not request.society_name or request.society_name == "the Society":
        soc_name = raw_payload.get("societyName")
        if soc_name:
            request.society_name = soc_name

    logger.info(
        "Authenticated secretary ID: %d (society_id: %s) sending message.",
        verified_secretary_id,
        request.society_id,
    )

    return StreamingResponse(
        chat_service.stream_chat(request),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",  # Disables proxy buffering (useful for Nginx in production)
        },
    )


@router.get(
    "/history",
    summary="Get permanent conversation history",
    description="Returns the full, chronological chat history for the authenticated secretary.",
    response_model=HistoryResponse,
    status_code=status.HTTP_200_OK,
)
async def get_chat_history(
    limit: int = Query(default=50, ge=1, le=200, description="Max messages to return"),
    skip: int = Query(default=0, ge=0, description="Messages to skip for pagination"),
    current_user: dict = Depends(get_current_secretary),
):
    """
    Retrieve permanent conversation history for UI display.
    Securely derives the thread_id from the authenticated caller's JWT token.
    """
    # Security: bound to the authenticated caller's verified ID
    thread_id = f"secretary_{current_user['user_id']}"

    messages = await history_service.get_history(thread_id=thread_id, limit=limit, skip=skip)
    total_count = await history_service.get_message_count(thread_id=thread_id)

    return HistoryResponse(
        thread_id=thread_id,
        messages=messages,
        total_count=total_count,
    )
